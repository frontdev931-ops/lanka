import { claimMatch, claimProblem } from '../src/ai/guardrails';

// The risk words of a model's free text (discount, guarantee, "painless", percentages): a promise is refused, a sentence that DENIES the promise is not
describe('слова-ризики в тексті моделі: обіцянка — так, заперечення обіцянки — ні', () => {
  const promises = [
    'Для вас знижка 20%',
    'Ми гарантуємо результат',
    'Це абсолютно безболісно',
    'Не боляче, обіцяємо',
    'Лікування безболезненно',
    'Для вас діє акція',
    'Консультація безкоштовна',
    'Ефект назавжди',
    'Розстрочка на пів року',
    'Вам знижка. Знижок немає для інших.',
  ];
  const denials = [
    'Ми не гарантуємо результат, його визначить лікар.',
    'Ми не можемо обіцяти знижку.',
    'Знижок немає.',
    'Ціни без знижок, лише прайс клініки.',
    'Ми не обіцяємо, що буде безболісно.',
    'Мы не гарантируем результат.',
    'Скидок нет.',
  ];
  it('обіцянка знижки, гарантії, безболісності, відсотків і «безкоштовно» відхиляється', () => {
    for (const t of promises) expect([t, claimProblem(t)]).toEqual([t, 'risky_claim']);
  });
  it('заперечення обіцянки («не гарантуємо», «знижок немає», «без знижок») пропускається', () => {
    for (const t of denials) expect([t, claimMatch(t)]).toEqual([t, null]);
  });
  it('слово назване точно: перше з обіцянок', () => {
    expect(claimMatch('Вітаємо! Для вас знижка 20%.')).toBe('20%');
    expect(claimMatch('Вітаємо! Для вас знижка.')).toBe('знижк');
    expect(claimMatch('Усе безболісно.')).toBe('безболісн');
  });
  it('звичайний текст без слів-ризиків проходить', () => {
    for (const t of ['Консультація триває близько 30 хвилин.', 'Лікар пояснює кожен крок і зупиняється за вашим сигналом.', 'Коштує 100 грн, уточнить адміністратор.']) expect([t, claimMatch(t)]).toEqual([t, null]);
  });
});
